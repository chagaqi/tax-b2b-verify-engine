import { describe, expect, it } from 'vitest';
import { RULES, TaxIdInputError, listJurisdictions, validateTaxId } from '../src/taxid/index.js';
import { iso7064Mod11_10, iso7064Mod97_10, luhnCheckChar, luhnValid } from '../src/taxid/algorithms.js';
import vectors from './fixtures/stdnum-vectors.json' with { type: 'json' };

type Vector = { country: string; input: string; valid: boolean };
const byCountry = new Map<string, Vector[]>();
for (const v of vectors.vectors as Vector[]) byCountry.set(v.country, [...(byCountry.get(v.country) ?? []), v]);

describe('jurisdiction coverage', () => {
  it('supports 49 jurisdictions (EU-27 + XI + 21 others)', () => {
    expect(RULES).toHaveLength(49);
    expect(new Set(RULES.map((r) => r.code)).size).toBe(49);
    expect(RULES.filter((r) => r.vies)).toHaveLength(28);
  });

  it('exposes public metadata without functions', () => {
    const list = listJurisdictions();
    expect(list.find((j) => j.code === 'GR')).toMatchObject({ country: 'GR', vies: true, scheme: 'eu_vat' });
    expect(JSON.parse(JSON.stringify(list))).toEqual(list);
  });
});

describe('every rule validates its documented example', () => {
  it.each(RULES.map((r) => [r.code, r.example, r.code === 'XI' ? 'XI' : r.country] as const))('%s %s', (_code, example, country) => {
    const v = validateTaxId(example, country);
    expect(v.valid).toBe(true);
    expect(v.syntaxValid).toBe(true);
    expect(v.checksum).not.toBe('invalid');
  });
});

describe('cross-validation against python-stdnum', () => {
  it(`fixture was generated by python-stdnum ${vectors.stdnumVersion}`, () => {
    expect(vectors.generator).toBe('python-stdnum');
    expect(vectors.vectors.length).toBeGreaterThan(1500);
  });

  it.each([...byCountry.keys()])('%s agrees with stdnum on every vector', (country) => {
    const mismatches = byCountry
      .get(country)!
      .filter((v) => {
        try {
          return validateTaxId(v.input, country).valid !== v.valid;
        } catch {
          return v.valid; // throwing on a valid number is a mismatch
        }
      })
      .map((v) => `${v.input} expected ${v.valid}`);
    expect(mismatches).toEqual([]);
  });
});

describe('a corrupted check character is rejected', () => {
  const checksummed = RULES.filter((r) => validateTaxId(r.example, r.code === 'XI' ? 'XI' : r.country).checksum === 'valid');

  it.each(checksummed.map((r) => [r.code, r] as const))('%s', (_code, rule) => {
    const country = rule.code === 'XI' ? 'XI' : rule.country;
    // Substitute every alternative at the check position; most must fail and none may crash.
    const base = rule.example.replace(/[\s.\-/]/g, '');
    // NL ends in a B01 branch suffix and CA in an RT0001 program account — the check digit precedes them.
    const pos = { NL: 10, CA: 8 }[rule.code] ?? base.length - 1;
    const orig = base[pos]!;
    const alphabet = /\d/.test(orig) ? '0123456789' : 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
    const outcomes = [...alphabet]
      .filter((ch) => ch !== orig)
      .map((ch) => validateTaxId(base.slice(0, pos) + ch + base.slice(pos + 1), country).valid);
    expect(outcomes.filter((ok) => !ok).length).toBeGreaterThan(outcomes.length / 2);
  });
});

describe('jurisdiction detection', () => {
  it.each([
    ['DE136695976', 'DE'],
    ['EL094259216', 'GR'],
    ['XI980780684', 'XI'],
    ['GB980780684', 'GB'],
    ['CHE-116.281.710 MWST', 'CH'],
    ['NO988077917MVA', 'NO'],
    ['27AAPFU0939F1ZV', 'IN'],
    ['ATU13585627', 'AT'],
  ])('%s → %s', (input, code) => {
    expect(validateTaxId(input).jurisdiction).toBe(code);
  });

  it('requires a country when the number has no prefix', () => {
    expect(() => validateTaxId('04-3341285')).toThrow(TaxIdInputError);
    try {
      validateTaxId('123456789');
    } catch (e) {
      expect((e as TaxIdInputError).code).toBe('country_required');
    }
  });

  it('rejects unknown countries and empty input', () => {
    expect(() => validateTaxId('123', 'ZZ')).toThrow(/Unsupported country/);
    expect(() => validateTaxId('  - . ')).toThrow(/empty/);
  });

  it('accepts EL/UK aliases and keeps XI when the caller says GB', () => {
    expect(validateTaxId('094259216', 'EL').jurisdiction).toBe('GR');
    expect(validateTaxId('980780684', 'UK').jurisdiction).toBe('GB');
    expect(validateTaxId('XI980780684', 'GB').jurisdiction).toBe('XI');
  });
});

describe('normalisation', () => {
  it('strips separators, case and the VAT prefix', () => {
    const v = validateTaxId(' de 136.695-976 ');
    expect(v.normalized).toBe('136695976');
    expect(v.formatted).toBe('DE136695976');
  });

  it('pads legacy Belgian (9-digit) and Greek (8-digit) numbers', () => {
    expect(validateTaxId('BE403019261').normalized).toBe('0403019261');
    expect(validateTaxId('EL94259216').normalized).toBe('094259216');
  });

  it('zero-pads short Dutch numbers and formats Greece with EL', () => {
    expect(validateTaxId('NL4495445B01').normalized).toBe('004495445B01');
    expect(validateTaxId('GR094259216').formatted).toBe('EL094259216');
  });

  it('applies national display formats for non-VIES schemes', () => {
    expect(validateTaxId('043341285', 'US').formatted).toBe('04-3341285');
    expect(validateTaxId('51824753556', 'AU').formatted).toBe('51 824 753 556');
    expect(validateTaxId('11222333000181', 'BR').formatted).toBe('11.222.333/0001-81');
    expect(validateTaxId('CHE116281710', 'CH').formatted).toBe('CHE-116.281.710');
    expect(validateTaxId('T5835678256246', 'JP').normalized).toBe('5835678256246');
  });
});

describe('scheme details', () => {
  it('reports the IRS campus for EINs and rejects unassigned prefixes', () => {
    expect(validateTaxId('04-3341285', 'US')).toMatchObject({ valid: true, checksum: 'not_applicable', details: { campus: 'Brookhaven' } });
    expect(validateTaxId('07-1234567', 'US')).toMatchObject({ valid: false, syntaxValid: false });
  });

  it('decodes GSTIN state, PAN and holder type', () => {
    expect(validateTaxId('27AAPFU0939F1ZV').details).toEqual({ state: 'Maharashtra', pan: 'AAPFU0939F', holderType: 'Firm/LLP' });
  });

  it('parses Canadian program accounts', () => {
    expect(validateTaxId('123456782 RT0001', 'CA').details).toEqual({ programAccount: 'RT', reference: '0001' });
    expect(validateTaxId('123456782XX0001', 'CA').valid).toBe(false);
  });

  it('distinguishes Australian ABN and ACN', () => {
    expect(validateTaxId('51 824 753 556', 'AU').details?.type).toBe('ABN');
    expect(validateTaxId('004 085 616', 'AU').details?.type).toBe('ACN');
  });

  it('treats the Mexican homoclave check digit as advisory', () => {
    const v = validateTaxId('GODE561231GR8', 'MX');
    expect(v).toMatchObject({ valid: true, checksum: 'not_applicable' });
    expect(v.details?.checkDigitMatches).toBe('true');
  });

  it('explains structural failures', () => {
    expect(validateTaxId('DE12345', 'DE')).toMatchObject({ valid: false, syntaxValid: false, reason: 'Expected 9 digits, got 5' });
    expect(validateTaxId('DE136695977').reason).toBe('Check digit mismatch');
  });
});

describe('check-digit primitives', () => {
  it('Luhn', () => {
    expect(luhnValid('79927398713')).toBe(true);
    expect(luhnValid('79927398710')).toBe(false);
    expect(luhnCheckChar('7992739871')).toBe('3');
  });

  it('ISO 7064 MOD 11,10 and MOD 97-10', () => {
    expect(iso7064Mod11_10('136695976')).toBe(1);
    expect(iso7064Mod97_10('GB82WEST12345698765432'.slice(4) + 'GB82')).toBe(1);
  });
});
